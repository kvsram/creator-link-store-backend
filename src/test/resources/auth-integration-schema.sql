drop table if exists tags;
drop table if exists auth_security_events;
drop table if exists password_reset_tokens;
drop table if exists email_verification_tokens;
drop table if exists auth_sessions;
drop table if exists account_login_state;
drop table if exists password_credentials;
drop table if exists account_phones;
drop table if exists account_emails;
drop table if exists creator_handles;
drop table if exists creator_profiles;
drop table if exists accounts;
drop table if exists sessions;
drop table if exists notification_preferences;
drop table if exists products;
drop table if exists links;
drop table if exists stores;
drop table if exists creators;

create table creators (
  id bigint generated by default as identity primary key,
  handle varchar(40) unique not null,
  display_name varchar(80) not null,
  email varchar(255) unique not null,
  phone varchar(32),
  password_hash varchar(255) not null,
  bio varchar(280) not null default '',
  avatar_url varchar(2048),
  created_at timestamp with time zone not null default current_timestamp
);

create table stores (
  id bigint generated by default as identity primary key,
  creator_id bigint unique not null references creators(id) on delete cascade,
  title varchar(100) not null,
  currency char(3) not null default 'INR',
  published boolean not null default true,
  payouts_enabled boolean not null default false
);

alter table stores add column tagline varchar(180) not null default 'Systems and templates for independent creators.';
alter table stores add column theme varchar(40) not null default 'violet';
alter table stores add column accent_color varchar(7) not null default '#6842d7';
alter table stores add column background_style varchar(30) not null default 'soft-gradient';
alter table stores add column button_style varchar(20) not null default 'rounded';
alter table stores add column font_style varchar(20) not null default 'modern';
alter table stores add column show_products boolean not null default true;
alter table stores add column show_links boolean not null default true;

create table links (
  id bigint generated by default as identity primary key,
  creator_id bigint not null references creators(id) on delete cascade,
  title varchar(100) not null,
  url varchar(2048) not null,
  description varchar(500) not null default '',
  brand_name varchar(100) not null default '',
  thumbnail_url varchar(2048),
  call_to_action varchar(60) not null default 'Visit link',
  coupon_code varchar(80) not null default '',
  offer_text varchar(120) not null default '',
  disclosure varchar(160) not null default '',
  position integer not null default 0,
  pinned boolean not null default false,
  published boolean not null default true,
  starts_at timestamp with time zone,
  ends_at timestamp with time zone
);

create table products (
  id bigint generated by default as identity primary key,
  creator_id bigint not null references creators(id) on delete cascade,
  type varchar(40) not null default 'digital-download',
  title varchar(100) not null,
  subtitle varchar(160) not null default '',
  call_to_action varchar(60) not null default 'Get access',
  thumbnail_style varchar(20) not null default 'preview',
  description varchar(2000) not null,
  price_cents integer not null default 0,
  thumbnail_url varchar(2048),
  pinned boolean not null default false,
  position integer not null default 0,
  configuration_json varchar(10000) not null default '{}',
  status varchar(20) not null default 'published'
);

create table notification_preferences (
  creator_id bigint primary key references creators(id) on delete cascade,
  order_emails boolean not null default true,
  marketing_emails boolean not null default true,
  payout_emails boolean not null default true
);

create table sessions (
  id varchar(64) primary key,
  creator_id bigint not null references creators(id) on delete cascade,
  created_at timestamp with time zone not null default current_timestamp,
  expires_at timestamp with time zone not null,
  revoked_at timestamp with time zone
);

create table accounts (
  id bigint primary key references creators(id) on delete cascade,
  public_id uuid not null default random_uuid() unique,
  status varchar(32) not null default 'active',
  session_version integer not null default 1,
  row_version bigint not null default 0,
  created_at timestamp with time zone not null default current_timestamp,
  updated_at timestamp with time zone not null default current_timestamp,
  deleted_at timestamp with time zone
);

create table creator_profiles (
  account_id bigint primary key references accounts(id) on delete cascade,
  display_name varchar(80) not null,
  bio varchar(280) not null default '',
  avatar_url varchar(2048),
  created_at timestamp with time zone not null default current_timestamp,
  updated_at timestamp with time zone not null default current_timestamp
);

create table creator_handles (
  handle varchar(40) primary key,
  account_id bigint references accounts(id) on delete cascade,
  state varchar(16) not null,
  claimed_at timestamp with time zone not null default current_timestamp,
  retired_at timestamp with time zone
);

create table account_emails (
  id bigint generated by default as identity primary key,
  account_id bigint not null references accounts(id) on delete cascade,
  email_original varchar(320) not null,
  email_normalized varchar(320) not null unique,
  is_primary boolean not null default false,
  verified_at timestamp with time zone,
  created_at timestamp with time zone not null default current_timestamp
);

create table account_phones (
  id bigint generated by default as identity primary key,
  account_id bigint not null references accounts(id) on delete cascade,
  phone_original varchar(32) not null,
  is_primary boolean not null default false,
  verified_at timestamp with time zone,
  created_at timestamp with time zone not null default current_timestamp
);

create table password_credentials (
  account_id bigint primary key references accounts(id) on delete cascade,
  verifier varchar(500) not null,
  legacy_verifier varchar(500),
  changed_at timestamp with time zone not null default current_timestamp,
  must_change boolean not null default false
);

create table account_login_state (
  account_id bigint primary key references accounts(id) on delete cascade,
  consecutive_failures integer not null default 0,
  failure_window_started_at timestamp with time zone,
  last_failed_at timestamp with time zone,
  locked_until timestamp with time zone,
  updated_at timestamp with time zone not null default current_timestamp
);

create table auth_sessions (
  id bigint generated by default as identity primary key,
  public_id uuid not null default random_uuid() unique,
  account_id bigint not null references accounts(id) on delete cascade,
  token_hash varchar(64) not null unique,
  session_version integer not null,
  auth_method varchar(32) not null default 'password',
  created_at timestamp with time zone not null default current_timestamp,
  last_seen_at timestamp with time zone not null default current_timestamp,
  idle_expires_at timestamp with time zone not null,
  absolute_expires_at timestamp with time zone not null,
  revoked_at timestamp with time zone,
  revocation_reason varchar(80),
  ip_hmac varchar(64),
  user_agent_hash varchar(64)
);

create table email_verification_tokens (
  id bigint generated by default as identity primary key,
  email_id bigint not null references account_emails(id) on delete cascade,
  token_hash varchar(64) not null unique,
  created_at timestamp with time zone not null default current_timestamp,
  expires_at timestamp with time zone not null,
  consumed_at timestamp with time zone
);

create table password_reset_tokens (
  id bigint generated by default as identity primary key,
  account_id bigint not null references accounts(id) on delete cascade,
  token_hash varchar(64) not null unique,
  created_at timestamp with time zone not null default current_timestamp,
  expires_at timestamp with time zone not null,
  consumed_at timestamp with time zone
);

create table auth_security_events (
  id bigint generated by default as identity primary key,
  account_id bigint references accounts(id) on delete set null,
  event_type varchar(64) not null,
  outcome varchar(24) not null,
  request_id varchar(80),
  identifier_hash varchar(64),
  ip_hmac varchar(64),
  user_agent_hash varchar(64),
  metadata_json varchar(2000) not null default '{}',
  occurred_at timestamp with time zone not null default current_timestamp
);
